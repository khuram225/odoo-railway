# -*- coding: utf-8 -*-
from odoo import _, api, fields, models
from odoo.exceptions import UserError

from odoo.addons.aw_fenestration_core.models.units import (
    to_display, to_mm,
)

# Half a sixteenth of an inch, rounded down: a length typed at display
# precision that lands this close to the computed one IS the computed one.
MANUAL_TOLERANCE_MM = 0.79

ROLE_SELECTION = [
    ('frame', 'Frame'),
    ('sash', 'Sash'),
    ('interlock', 'Interlock'),
    ('bead', 'Glazing Bead'),
    ('mesh', 'Mesh'),
]


class AwDesignBomLine(models.Model):
    """One cut piece — the direct port of what the prototype's explode()
    pushed into its prof[] array, each carrying a {ref, loc, row, leaf,
    where} tag for the cumulative cut-list traceability (point #1 from
    the original planning: one growing table across every window in an
    order, each piece traceable back to which window/row/leaf it belongs
    to). GENERATED by action_explode() on aw.design — never hand-entered,
    same as the prototype's BOM was always computed, never typed in.

    Nesting into stock bars (14/16/18 ft), yield %, wastage reconciliation
    and the cumulative multi-design cut table are NOT part of this model —
    those operate across every aw.design on an order at once (same as the
    prototype's cutPlan() pooled pieces across every QUOTE.designs[]
    entry), so they belong on a report/wizard keyed off sale.order, not
    stored per-line here.
    """
    _name = 'aw.design.bom.line'
    _description = 'Fenestration Design BOM Line'
    _order = 'design_id, sequence, id'

    design_id = fields.Many2one('aw.design', required=True, ondelete='cascade', index=True)
    sequence = fields.Integer(default=10)

    # kind replaces role as what the engine writes. role is kept and no
    # longer required: it was the dormant frame/sash/interlock/bead/mesh
    # Selection from before positions existed, and dropping it would lose
    # whatever an old row said.
    kind = fields.Selection([
        ('profile', 'Profile'),
        ('glass', 'Glass'),
        ('hardware', 'Hardware'),
        ('mesh', 'Mesh'),
        ('infill', 'Infill'),
        ('grid', 'Grid'),
    ], required=True, default='profile', index=True)
    role = fields.Selection(ROLE_SELECTION)
    # Not required: the engine still reports a line whose product is
    # missing, because a silent gap in a cut list is worse than a line
    # that says what is wrong. The checks flag it.
    product_id = fields.Many2one('product.product', ondelete='restrict')

    length_mm = fields.Float()
    cut_angle = fields.Selection([
        ('45', '45 deg'), ('90', '90 deg'),
    ], default='90')
    label = fields.Char(help="Where this piece goes, e.g. 'P2 Palay - Top'.")
    # Stable identity for one physical piece (spec 6c-B). Assigned by
    # the explosion from the design's own geometry, so it survives
    # re-optimising the cutting plan -- which is the whole point: the
    # shop writes it on the bar.
    # -- how this length was reached, for manual verification ----------
    # Written by the explosion, never computed on read: the BOM is the
    # record of what was quoted, and a rule edited next month must not
    # silently restate the working of a piece already priced and sent.
    # Same reasoning as is_changed/change_note above.
    calc_rule = fields.Char(
        string='Rule', readonly=True,
        help="The formula as written, e.g. 'PW - 10'.")
    calc_source = fields.Char(
        string='Source', readonly=True,
        help="Where the rule came from: the spec's own line, or the "
             "profile position's default.")
    calc_worked = fields.Char(
        string='Worked out', readonly=True,
        help="The formula with the values used, e.g. '1066.8 - 10'.")
    # Glass is two dimensions from two rules. Width uses the three
    # fields above; these carry the height, whose source is the same.
    calc_rule_h = fields.Char(string='Rule (height)', readonly=True)
    calc_worked_h = fields.Char(string='Worked out (height)', readonly=True)

    piece_ref = fields.Char(string='Ref', index=True)
    unit_no = fields.Integer(
        string='Unit', default=1,
        help="Which of the position's units this piece belongs to.")
    panel_no = fields.Integer(string='Panel')

    # -- phase 7c ------------------------------------------------------
    # Stored on the LINE rather than derived on read: the BOM is the
    # record of what was quoted, and an override deleted afterwards must
    # not silently rewrite a line that was already priced and sent.
    is_changed = fields.Boolean(
        string='Changed',
        help="This line differs from the window's Specification, "
             "because it was changed for this window.")
    change_note = fields.Char(
        string='Change Note',
        help="Why this window is different. Printed on the shop "
             "drawing beside the line.")
    glass_spec_id = fields.Many2one('aw.glass.spec', ondelete='restrict')
    glass_w = fields.Float(string='Width (mm)')
    glass_h = fields.Float(string='Height (mm)')
    area_sqm = fields.Float(compute='_compute_area_sqm', store=True)
    qty = fields.Integer(required=True, default=1,
        help="Pieces of this exact length needed — e.g. 2 for a pair of "
             "top/bottom rails. Multiply by aw.design.qty for the total "
             "physical count across all units of this design.")

    # traceability tag — matches the prototype's tag:{ref,loc,row,leaf,where}
    row_index = fields.Integer(string='Row #')
    leaf_index = fields.Integer(string='Leaf #')
    where = fields.Char(help="Human-readable location, e.g. 'sash top/bottom', "
        "'vertical mullion' — matches the prototype's tag.where used on "
        "the Report tab's cut list.")

    unit_cost = fields.Float(
        help="Rate at time of explosion (PKR/ft or equivalent) — snapshot, "
             "not a live lookup, same reasoning as the earlier decision "
             "that a quote must not silently recost when reopened.")

    # -- the cut list's own bookkeeping -------------------------------
    template_line_id = fields.Many2one(
        'aw.profile.section.line', string='Template Line',
        ondelete='set null',
        help="The spec line this piece came from. Empty for a line "
             "added by hand.")
    piece_key = fields.Char(
        index=True, copy=True,
        help="Which piece of which spec line, panel and unit this is. "
             "How an edited line finds itself again after a recompute.")
    group_label = fields.Char(
        string='Group',
        help="The spec section the piece comes from: Frame, Sliding "
             "panel, Joints...")
    cut_on_site = fields.Boolean(
        string='Cut on site',
        help="No length is worked out; cut at the job.")
    computed_length_mm = fields.Float(
        string='Computed (mm)', readonly=True,
        help="What the spec's rule gives. Length is this until somebody "
             "edits it.")
    is_manual = fields.Boolean(
        string='Manual', default=False,
        help="Length, quantity or section was edited by hand. A "
             "recompute re-applies such a line instead of overwriting it.")
    is_orphan = fields.Boolean(
        string='Orphan', default=False, copy=False,
        help="A line edited by hand whose piece no longer exists after "
             "the last recompute (a panel was removed, a rule changed). "
             "It is kept as typed so nothing is lost silently; fix it or "
             "delete it.")
    is_free_form = fields.Boolean(
        string='Free-form', default=False,
        help="Added by hand, not from the spec. A recompute never "
             "changes or deletes it.")
    length_text = fields.Char(
        string='Length (in)', compute='_compute_length_texts',
        inverse='_inverse_length_text',
        help="Inches and soot: 34 1/8, 33-6, 3s, 1829mm. Stored in mm.")
    computed_length_text = fields.Char(
        string='Computed (in)', compute='_compute_length_texts')

    @api.depends('length_mm', 'computed_length_mm', 'cut_on_site')
    def _compute_length_texts(self):
        for line in self:
            line.length_text = (
                '' if line.cut_on_site
                else to_display(line.length_mm, 'soot'))
            line.computed_length_text = (
                '' if line.cut_on_site
                else to_display(line.computed_length_mm, 'soot'))

    def _inverse_length_text(self):
        for line in self:
            # Typing back what is already shown is not an edit, and must
            # not flag the line manual or move it to the nearest 1/16.
            if (line.length_text or '') == (
                    '' if line.cut_on_site
                    else to_display(line.length_mm, 'soot')):
                continue
            try:
                line.length_mm = to_mm(line.length_text)
            except ValueError:
                raise UserError(_(
                    "'%(text)s' cannot be read as a length. Use inches "
                    "(72, 34 1/8), soot (3s, 33-6) or millimetres "
                    "(1829mm).", text=line.length_text))

    @api.onchange('length_text')
    def _onchange_length_text(self):
        """Typing inches updates the mm column at once, before the row
        is saved; typing mm updates the text through its compute. The
        text is only re-formatted when the cell is committed."""
        for line in self:
            try:
                mm = to_mm(line.length_text)
            except ValueError:
                continue
            computed = line._computed_if_close(mm)
            if computed is not None:
                mm = computed
            if abs(mm - (line.length_mm or 0.0)) > 0.005:
                line.length_mm = mm

    def _computed_if_close(self, mm):
        """The computed length when `mm` is within display precision of
        it, else None. Only generated pieces have a computed length to
        compare with; a free-form line has none."""
        self.ensure_one()
        if (self.piece_key and not self.is_free_form
                and abs(mm - (self.computed_length_mm or 0.0))
                <= MANUAL_TOLERANCE_MM):
            return self.computed_length_mm
        return None

    def write(self, vals):
        # Editing a generated piece by hand makes it MANUAL, so the next
        # recompute keeps it. The generator itself writes under
        # `aw_bom_generating` and must not flag anything.
        if (not self.env.context.get('aw_bom_generating')
                and 'is_manual' not in vals
                and any(k in vals for k in (
                    'length_mm', 'qty', 'product_id'))):
            # A length entered at display precision that matches the
            # computed one is not an edit: store the computed value and
            # do not flag it.
            if ('length_mm' in vals and not any(
                    k in vals for k in ('qty', 'product_id'))):
                for line in self:
                    own = dict(vals)
                    computed = line._computed_if_close(vals['length_mm'])
                    if computed is not None:
                        own['length_mm'] = computed
                    else:
                        own['is_manual'] = True
                    super(AwDesignBomLine, line).write(own)
                return True
            vals = dict(vals, is_manual=True)
        return super().write(vals)

    @api.depends('glass_w', 'glass_h', 'qty')
    def _compute_area_sqm(self):
        for line in self:
            line.area_sqm = (
                (line.glass_w or 0.0) * (line.glass_h or 0.0)
                / 1000000.0 * (line.qty or 0))
