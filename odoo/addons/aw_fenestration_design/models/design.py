# -*- coding: utf-8 -*-
import json

from odoo import _, api, fields, models
from odoo.exceptions import UserError


class AwDesign(models.Model):
    """One configured window/door position — the direct port of the JS
    prototype's QUOTE.designs[] entry. The one deliberate departure from
    the prototype: this ties to a real sale.order.line instead of living
    in a standalone quote object, so Odoo's own pricing/discount/tax/PDF/
    portal machinery applies rather than being rebuilt in parallel.

    Row/leaf geometry lives in aw.design.row / aw.design.leaf (children).
    Profile cut list lives in aw.design.bom.line, GENERATED by the
    explosion engine — not part of this module yet, see action_explode().
    """
    _name = 'aw.design'
    _inherit = ['mail.thread', 'mail.activity.mixin']
    _description = 'Fenestration Design'
    _order = 'id'

    name = fields.Char(
        required=True, tracking=True,
        help="Position reference, e.g. 'D1' — matches the prototype's "
             "design.ref, shown on the cumulative cut-list table.")
    location = fields.Char(tracking=True, help="e.g. 'Drawing room', "
        "'Bathroom' — matches the prototype's design.loc.")
    qty = fields.Integer(default=1, required=True, tracking=True)
    active = fields.Boolean(default=True)

    # length_uom is NOT related to any stored field on res.company -- it's
    # a plain non-stored compute reading ir.config_parameter directly (see
    # aw_fenestration_core's res_config_settings.py for why: a required
    # stored field on a core model that's prefetched on every request is
    # exactly the risk class that took the whole site down once already).
    length_uom = fields.Selection([
        ('ftin', 'Feet + Inches'),
        ('in', 'Inches'),
        ('mm', 'Millimetres'),
    ], compute='_compute_length_uom', string='Length Unit')

    # -- geometry, overall opening --------------------------------------
    # mm is the stored source of truth; ft/in and inch_total are
    # compute+inverse display/entry pairs that read from and write back
    # to it, so editing in ANY unit keeps all three in sync and the view
    # can show only the pair matching length_uom.
    #
    # Deliberately NOT required=True. Two separate paths create a design
    # before any dimension is known: Add Position (which creates the
    # design, then opens its form to be filled in), and a new design form
    # where the user types into the ft/in pair -- those are non-stored
    # inverse fields, and the NOT NULL constraint fires at INSERT, before
    # the inverse that would populate *_mm ever runs. Both hit
    # "Missing required value for the field 'Width (mm)'". Zero is a
    # legitimate not-yet-filled-in state here; see
    # _check_dimensions_set(), which enforces real dimensions at the two
    # points where they actually have to exist.
    width_mm = fields.Float(string='Width (mm)', default=0.0, tracking=True)
    width_ft = fields.Integer(string='Width (ft)',
        compute='_compute_width_ftin', inverse='_inverse_width_ftin')
    width_in = fields.Float(string='Width (in)',
        compute='_compute_width_ftin', inverse='_inverse_width_ftin',
        help="Decimals allowed, e.g. 6.5.")
    width_inch_total = fields.Float(string='Width (in)',
        compute='_compute_width_inch_total', inverse='_inverse_width_inch_total')

    height_mm = fields.Float(string='Height (mm)', default=0.0, tracking=True)
    height_ft = fields.Integer(string='Height (ft)',
        compute='_compute_height_ftin', inverse='_inverse_height_ftin')
    height_in = fields.Float(string='Height (in)',
        compute='_compute_height_ftin', inverse='_inverse_height_ftin',
        help="Decimals allowed, e.g. 6.5.")
    height_inch_total = fields.Float(string='Height (in)',
        compute='_compute_height_inch_total', inverse='_inverse_height_inch_total')

    # -- master-data links -----------------------------------------------
    # Confirmed against models/window_template.py: window_type_id is still
    # the exact field name on aw.window.template (and aw.profile.section/
    # aw.hardware.set), unchanged across the Kind/Type/Series restructure —
    # only its comodel moved to aw.window.series. Domain below is correct.
    window_series_id = fields.Many2one(
        'aw.window.series', required=True, tracking=True, ondelete='restrict')
    template_id = fields.Many2one(
        'aw.window.template', tracking=True, ondelete='set null',
        domain="[('window_type_id', '=', window_series_id)]",
        help="Optional starting default — populates Profile Section / "
             "Hardware Set / Glass Spec choices below when picked. Not "
             "required: a design can be built without one.")
    # Computed store=True readonly=False, like the rule sets below: a new
    # design picks up the Series' default glass, but the compute only
    # ever FILLS an empty value, so changing Series never silently
    # replaces glass someone chose.
    glass_spec_id = fields.Many2one(
        'aw.glass.spec', tracking=True, ondelete='restrict',
        compute='_compute_glass_spec', store=True, readonly=False)

    # -- which rules this design is built to (spec 6, addition A) ----------
    # Computed with store=True and readonly=False: they follow the Series
    # when it changes, which is what you want nine times out of ten, but
    # stay overridable for the tenth. A plain default would not reset on
    # a Series change; a plain related would not be overridable.
    profile_section_id = fields.Many2one(
        'aw.profile.section', string='Profile Section',
        compute='_compute_rule_sets', store=True, readonly=False,
        domain="[('window_type_id', '=', window_series_id)]",
        tracking=True, ondelete='restrict')
    hardware_set_id = fields.Many2one(
        'aw.hardware.set', string='Hardware Set',
        compute='_compute_rule_sets', store=True, readonly=False,
        domain="[('window_type_id', '=', window_series_id)]",
        tracking=True, ondelete='restrict')

    # -- finish / thickness -----------------------------------------------
    # These are product.attribute.value records (the Finish/Thickness
    # attributes created for the profile product import), not a hardcoded
    # Selection — so this module never has its own copy of "what finishes
    # exist" to keep in sync with the product catalogue. Confirmed the
    # attribute names against the live import: "Finish" (xmlid
    # aw_attribute_finish) and "Thickness" (xmlid aw_attribute_thickness)
    # in aw_fenestration_core/data/chawla_attributes_data.xml. Domains by
    # xmlid rather than by name string, matching the pattern already used
    # for categ_id in aw_fenestration_core's profile_section.py/
    # hardware_set.py/glass_spec.py -- a renamed attribute wouldn't
    # silently break this the way name-matching would.
    finish_id = fields.Many2one(
        'product.attribute.value', tracking=True,
        domain=lambda self: [(
            'attribute_id', '=',
            self.env.ref('aw_fenestration_core.aw_attribute_finish').id,
        )])
    thickness_id = fields.Many2one(
        'product.attribute.value', tracking=True,
        domain=lambda self: [(
            'attribute_id', '=',
            self.env.ref('aw_fenestration_core.aw_attribute_thickness').id,
        )])

    # -- pricing override, matches prototype's d.manual -------------------
    manual_rate = fields.Float(
        string='Manual Rate (per sqft)',
        help="If set, overrides the calculated rate — matches the "
             "prototype's manual-override mechanism. Leave blank to use "
             "calculated pricing once the cost cascade exists.")

    # -- Sale integration ---------------------------------------------------
    sale_order_line_id = fields.Many2one(
        'sale.order.line', ondelete='cascade', index=True,
        help="The line this design prices onto. May be blank while a "
             "design is still being configured pre-quote.")
    sale_order_id = fields.Many2one(
        related='sale_order_line_id.order_id', store=True, readonly=True)

    # -- children -----------------------------------------------------------
    # Top-level rows only. Nested rows carry the same design_id (so "all
    # rows of this design" stays one query) and are reached through their
    # parent leaf's child_row_ids instead -- without this domain they would
    # also show up here and the drawing would render them twice.
    row_ids = fields.One2many(
        'aw.design.row', 'design_id', string='Rows',
        domain=[('parent_leaf_id', '=', False)])
    bom_line_ids = fields.One2many(
        'aw.design.bom.line', 'design_id', string='Bill of Materials')

    row_count = fields.Integer(compute='_compute_counts')
    leaf_count = fields.Integer(compute='_compute_counts')
    size_display = fields.Char(compute='_compute_size_display', string='Size')
    area_sqm = fields.Float(compute='_compute_area', store=True, string='Area (m²)')
    area_sqft = fields.Float(compute='_compute_area', store=True, string='Area (sqft)')

    @api.depends('window_series_id')
    def _compute_glass_spec(self):
        """Fill from the Series' default, never replace.

        Assigning on every record is deliberate: a stored compute that
        leaves one unassigned raises, and `or` expresses the rule
        exactly -- keep what is there, otherwise take the default.
        """
        for design in self:
            design.glass_spec_id = (
                design.glass_spec_id
                or design.window_series_id.default_glass_spec_id)

    @api.depends('window_series_id')
    def _compute_rule_sets(self):
        """Follow the Series, keeping a choice that still fits it."""
        for design in self:
            series = design.window_series_id
            section = design.profile_section_id
            if not section or section.window_type_id != series:
                section = series.profile_section_ids[:1]
            design.profile_section_id = section
            hardware = design.hardware_set_id
            if not hardware or hardware.window_type_id != series:
                hardware = series.hardware_set_ids[:1]
            design.hardware_set_id = hardware

    @api.onchange('template_id')
    def _onchange_template(self):
        """A Window Template is exactly the bundle of Profile Section +
        Hardware Set + Glass, so picking one sets all three."""
        for design in self:
            template = design.template_id
            if not template:
                continue
            if template.profile_section_id:
                design.profile_section_id = template.profile_section_id
            if template.hardware_set_id:
                design.hardware_set_id = template.hardware_set_id
            if template.glass_spec_id:
                design.glass_spec_id = template.glass_spec_id

    @api.depends('row_ids.leaf_ids', 'row_ids.leaf_ids.child_row_ids')
    def _compute_counts(self):
        # leaf_count is PANELS, so it recurses and skips containers -- a
        # design whose only leaf is subdivided into two has two panels,
        # not one. row_count stays top-level, matching the stat button's
        # "Rows" action, which lists top-level rows.
        def panels(rows):
            return sum(
                panels(leaf.child_row_ids) if leaf.child_row_ids else 1
                for row in rows for leaf in row.leaf_ids)

        for rec in self:
            rec.row_count = len(rec.row_ids)
            rec.leaf_count = panels(rec.row_ids)

    @api.depends()
    def _compute_length_uom(self):
        value = self.env['ir.config_parameter'].sudo().get_param(
            'aw_fenestration.length_uom', 'ftin')
        for rec in self:
            rec.length_uom = value

    @api.depends('width_mm')
    def _compute_width_ftin(self):
        for rec in self:
            total_in = rec.width_mm / 25.4
            ft = int(total_in // 12)
            rec.width_ft = ft
            rec.width_in = total_in - ft * 12

    def _inverse_width_ftin(self):
        for rec in self:
            rec.width_mm = rec.width_ft * 304.8 + rec.width_in * 25.4

    @api.depends('width_mm')
    def _compute_width_inch_total(self):
        for rec in self:
            rec.width_inch_total = rec.width_mm / 25.4

    def _inverse_width_inch_total(self):
        for rec in self:
            rec.width_mm = rec.width_inch_total * 25.4

    @api.depends('height_mm')
    def _compute_height_ftin(self):
        for rec in self:
            total_in = rec.height_mm / 25.4
            ft = int(total_in // 12)
            rec.height_ft = ft
            rec.height_in = total_in - ft * 12

    def _inverse_height_ftin(self):
        for rec in self:
            rec.height_mm = rec.height_ft * 304.8 + rec.height_in * 25.4

    @api.depends('height_mm')
    def _compute_height_inch_total(self):
        for rec in self:
            rec.height_inch_total = rec.height_mm / 25.4

    def _inverse_height_inch_total(self):
        for rec in self:
            rec.height_mm = rec.height_inch_total * 25.4

    @api.depends('width_mm', 'height_mm', 'length_uom')
    def _compute_size_display(self):
        for rec in self:
            if rec.length_uom == 'mm':
                # One trailing unit reads better when both numbers carry
                # the same one; ft/in can't do that, each part needs its own.
                rec.size_display = '%s × %s mm' % (
                    rec._trim(rec.width_mm), rec._trim(rec.height_mm))
            else:
                rec.size_display = '%s × %s' % (
                    rec._format_length(rec.width_mm),
                    rec._format_length(rec.height_mm),
                )

    @staticmethod
    def _trim(value):
        # 6.0 -> "6", 6.5 -> "6.5" — no trailing ".0" in a quote line
        return ('%.2f' % value).rstrip('0').rstrip('.') or '0'

    def _format_length(self, mm):
        """One length, rendered in whatever unit the Fenestration setting
        is currently on. Used for the sale line description and the Sale
        Order's Fenestration tab, so both always speak the same unit the
        design form is being edited in."""
        if self.length_uom == 'mm':
            return '%s mm' % self._trim(mm)
        total_in = mm / 25.4
        if self.length_uom == 'in':
            return '%s in' % self._trim(total_in)
        ft = int(total_in // 12)
        return '%s ft %s in' % (ft, self._trim(total_in - ft * 12))

    @api.depends('width_mm', 'height_mm')
    def _compute_area(self):
        for rec in self:
            m2 = (rec.width_mm / 1000.0) * (rec.height_mm / 1000.0)
            rec.area_sqm = m2
            rec.area_sqft = m2 * 10.7639

    # -- sale.order.line sync ----------------------------------------------
    # Done in create()/write(), NOT onchange: a design is edited on its own
    # form, not embedded in the Sale Order form, so there's no in-memory
    # parent record for an onchange to write back into. Confirmed this is
    # how core handles the same shape -- repair.repair.write() calls
    # _update_sale_order_line_price() to push onto its own sale_line_id
    # after super(), rather than relying on any onchange.
    SALE_LINE_SYNC_FIELDS = (
        'name', 'location', 'window_series_id', 'width_mm', 'height_mm',
        'qty', 'manual_rate', 'sale_order_line_id',
    )

    def _prepare_sale_line_description(self):
        self.ensure_one()
        parts = [self.name or '', self.location or '', self.size_display or '']
        if self.window_series_id:
            parts.append(self.window_series_id.display_name)
        return ' — '.join(p for p in parts if p)

    def _sync_sale_order_line(self):
        for rec in self:
            line = rec.sale_order_line_id
            if not line:
                continue
            vals = {
                'name': rec._prepare_sale_line_description(),
                'product_uom_qty': rec.qty,
            }
            # Only touch price_unit when there's an explicit manual rate --
            # otherwise leave whatever Odoo's own pricelist logic put there
            # alone. Real cost-cascade pricing is Step 3, not this one.
            if rec.manual_rate:
                vals['price_unit'] = rec.manual_rate * rec.area_sqft
            line.write(vals)

    @api.model_create_multi
    def create(self, vals_list):
        designs = super().create(vals_list)
        designs._sync_sale_order_line()
        return designs

    def write(self, vals):
        res = super().write(vals)
        if any(f in vals for f in self.SALE_LINE_SYNC_FIELDS):
            self._sync_sale_order_line()
        return res

    def unlink(self):
        # Deleting a design removes the quote line it priced onto. The
        # reverse already works without any code: sale_order_line_id is
        # ondelete='cascade', so deleting the line drops the design at the
        # DB level. Lines are collected before super() so the cascade has
        # nothing left to chase by the time they're unlinked.
        lines = self.sale_order_line_id
        res = super().unlink()
        lines.unlink()
        return res

    def action_open_design(self):
        self.ensure_one()
        return {
            'type': 'ir.actions.act_window',
            'res_model': 'aw.design',
            'res_id': self.id,
            'view_mode': 'form',
            'views': [(False, 'form')],
            'target': 'current',
        }

    # -- visual configurator -----------------------------------------------
    # Everything the configurator can write, as an explicit allow-list.
    # save_layout() is a public RPC method any sales user can call with an
    # arbitrary dict, so the header payload is filtered against this rather
    # than passed to write() as-is -- otherwise a crafted call could set
    # sale_order_line_id and re-point a design at someone else's quote line.
    CONFIGURATOR_HEADER_FIELDS = (
        'name', 'location', 'qty', 'width_mm', 'height_mm',
        'window_series_id', 'glass_spec_id', 'finish_id', 'thickness_id',
        'profile_section_id', 'hardware_set_id',
        'manual_rate',
    )

    # Header fields a save must never blank just because the value was
    # absent from the payload. Every one of these can be hidden in the
    # configurator -- the Profile Section and Hardware Set dropdowns only
    # appear when the Series offers a choice, Thickness is hidden
    # outright, and manual_rate has no control at all -- and a control
    # that is not rendered sends nothing. Writing "nothing" as False
    # silently destroyed real data: manual_rate, a hand-entered price
    # override, was wiped by every single configurator save.
    #
    # Absent or None means "not sent, leave it alone". An explicit False
    # is a real instruction to clear, which is what "No glass" in the
    # header does, so the two cannot be collapsed.
    CONFIGURATOR_PROTECTED_HEADER = (
        'profile_section_id', 'hardware_set_id', 'glass_spec_id',
        'finish_id', 'thickness_id', 'manual_rate',
    )

    def action_open_configurator(self):
        self.ensure_one()
        return {
            'type': 'ir.actions.client',
            'tag': 'aw_design_configurator',
            'name': self.display_name,
            'params': {'design_id': self.id},
            'context': {'active_id': self.id, 'active_model': 'aw.design'},
        }

    def _renumber_panels(self):
        """Number every panel 1..n in reading order: rows top to bottom,
        leaves left to right, descending into a subdivided panel in place.

        Container leaves are not panels and get no number -- their
        children are numbered where the container sits, so splitting
        panel 2 turns it into panels 2 and 3 and pushes what was 3 to 4.
        """
        def walk(rows, number):
            for row in rows:
                for leaf in row.leaf_ids:
                    if leaf.child_row_ids:
                        leaf.panel_no = 0
                        number = walk(leaf.child_row_ids, number)
                    else:
                        number += 1
                        leaf.panel_no = number
            return number

        for design in self:
            walk(design.row_ids, 0)

    @api.model
    def _rows_payload(self, rows):
        """Serialise a row list, recursing into subdivided panels. A
        container leaf carries its own `rows` and no panel attributes."""
        return [{
            'height_mm': row.height_mm,
            'is_auto': row.is_auto,
            'leaves': [{
                'width_mm': leaf.width_mm,
                'is_auto': leaf.is_auto,
                'panel_no': leaf.panel_no,
                'is_container': bool(leaf.child_row_ids),
                'leaf_type_id': leaf.leaf_type_id.id,
                'leaf_type_code': leaf.leaf_type_id.code or '',
                'hinge_side': leaf.hinge_side or '',
                'swing': leaf.swing or '',
                'slide_dir': leaf.slide_dir or '',
                'junction_after': leaf.junction_after or '',
                'track_no': leaf.track_no or 0,
                'mesh_type_id': leaf.mesh_type_id.id,
                'mesh_type_code': leaf.mesh_type_id.code or '',
                'mesh_hinge_side': leaf.mesh_hinge_side or '',
                'infill_type_id': leaf.infill_type_id.id,
                'infill_kind': leaf.infill_type_id.kind or 'glass',
                'infill_uses_glass': (
                    leaf.infill_type_id.uses_glass
                    if leaf.infill_type_id else True),
                'glass_spec_id': leaf.glass_spec_id.id,
                'grid_pattern_id': leaf.grid_pattern_id.id,
                'grid_rows': leaf.grid_rows or 0,
                'grid_cols': leaf.grid_cols or 0,
                'rows': self._rows_payload(leaf.child_row_ids),
            } for leaf in row.leaf_ids],
        } for row in rows]

    @api.model
    def get_series_context(self, series_id):
        """Everything that depends on WHICH Series is chosen: the leaf
        types it can host and the presets that fit them.

        Separate from get_configurator_data so switching Series in the
        configurator refetches only this, leaving the layout the user is
        working on untouched.
        """
        series = self.env['aw.window.series'].browse(series_id).exists()
        presets = self.env['aw.layout.preset'].search(
            [])._allowed_for_series(series) if series else self.env[
                'aw.layout.preset']
        return {
            'leaf_types': [{
                'id': lt.id,
                'code': lt.code or '',
                'name': lt.display_name,
                'has_hinge_side': lt.has_hinge_side,
                'has_slide_dir': lt.has_slide_dir,
            } for lt in series.leaf_type_ids],
            'presets': [self._preset_payload(p) for p in presets],
            'families': self._families_payload(presets),
            # So the header's Profile Section / Hardware Set dropdowns
            # and the Series' default glass follow a Series change
            # without a reload.
            **self._rule_set_options(series),
            'default_glass_spec_id': series.default_glass_spec_id.id,
            **self._attachment_catalogue(),
        }

    @api.model
    def _rule_set_options(self, series):
        """The Profile Sections and Hardware Sets this Series offers."""
        return {
            'section_options': [
                {'id': s.id, 'name': s.display_name}
                for s in series.profile_section_ids],
            'hardware_options': [
                {'id': h.id, 'name': h.display_name}
                for h in series.hardware_set_ids],
        }

    @api.model
    def _finish_options(self):
        """Finish attribute values, for the header dropdown. Read off the
        attribute by xmlid rather than by name, matching finish_id's own
        domain -- a renamed attribute errors instead of silently
        returning nothing."""
        attribute = self.env.ref(
            'aw_fenestration_core.aw_attribute_finish',
            raise_if_not_found=False)
        if not attribute:
            return []
        return [{'id': v.id, 'name': v.display_name}
                for v in self.env['product.attribute.value'].search(
                    [('attribute_id', '=', attribute.id)])]

    @api.model
    def _attachment_catalogue(self):
        """Mesh, infill, glass and grid choices for the right panel and
        the library's mesh/infill families."""
        return {
            'mesh_types': [{
                'id': m.id, 'name': m.display_name, 'code': m.code or '',
                'mechanism': m.mechanism, 'pull': m.pull or '',
                'family_id': m.family_id.id or False,
                'family_name': m.family_id.name or '',
                'family_sequence': (
                    m.family_id.sequence if m.family_id else 999),
            } for m in self.env['aw.mesh.type'].search([])],
            'infill_types': [{
                'id': i.id, 'name': i.display_name, 'code': i.code or '',
                'kind': i.kind, 'uses_glass': i.uses_glass,
                'family_id': i.family_id.id or False,
                'family_name': i.family_id.name or '',
                'family_sequence': (
                    i.family_id.sequence if i.family_id else 999),
            } for i in self.env['aw.infill.type'].search([])],
            'glass_specs': [{
                'id': g.id, 'name': g.display_name,
            } for g in self.env['aw.glass.spec'].search([])],
            'grid_patterns': [{
                'id': g.id, 'name': g.display_name, 'code': g.code or '',
                'kind': g.kind,
            } for g in self.env['aw.grid.pattern'].search([])],
        }

    @api.model
    def _families_payload(self, presets):
        """Every family with something behind it, layout or attachment.

        A layout family earns its tile by having a preset available for
        this Series. Mesh and infill families hold TYPES, not presets, so
        the preset rule filtered them out entirely and the strip showed
        only layout families. They are counted by their own contents
        instead.
        """
        counts = {}
        for preset in presets:
            if preset.family_id:
                counts[preset.family_id.id] = counts.get(
                    preset.family_id.id, 0) + 1
        for mesh in self.env['aw.mesh.type'].search([]):
            if mesh.family_id:
                counts[mesh.family_id.id] = counts.get(
                    mesh.family_id.id, 0) + 1
        for infill in self.env['aw.infill.type'].search([]):
            if infill.family_id:
                counts[infill.family_id.id] = counts.get(
                    infill.family_id.id, 0) + 1

        families = self.env['aw.layout.family'].browse(
            list(counts)).sorted(lambda f: (f.sequence, f.name))
        return [{
            'id': f.id,
            'name': f.name,
            'code': f.code or '',
            'kind': f.kind,
            'has_image': bool(f.image_128),
            # Drawn when there's no picture: the first preset's layout.
            # A mesh or infill family has none, and its tile falls back
            # to an empty frame, which is honest enough for a heading.
            'preview': (
                json.loads(f.preview_layout_json)
                if f.preview_layout_json else None),
            'count': counts[f.id],
        } for f in families]

