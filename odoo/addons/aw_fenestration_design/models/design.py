    # A panel may be subdivided, its sub-panels subdivided again, and no
    # further. Three levels is what the spec allows and it is enforced on
    # the server as well as hidden in the UI, because save_layout is a
    # public RPC and a hand-built payload would otherwise be able to nest
    # without limit.
    MAX_NESTING_DEPTH = 3

    def _create_rows(self, rows, parent_leaf=None, depth=1):
        """Create a row list, recursing into subdivided panels.

        Rows are created one level at a time rather than with nested
        (0, 0, ...) commands because a child row needs its parent LEAF's
        database id, which doesn't exist until that leaf is written.
        """
        if depth > self.MAX_NESTING_DEPTH:
            raise UserError(_(
                "Panels can only be subdivided %s levels deep.",
                self.MAX_NESTING_DEPTH))
        for row in rows:
            record = self.env['aw.design.row'].create({
                'design_id': self.id,
                'parent_leaf_id': parent_leaf.id if parent_leaf else False,
                'height_mm': row.get('height_mm') or 0.0,
                'is_auto': row.get('is_auto', False),
                'leaf_ids': [(0, 0, {
                    'width_mm': leaf.get('width_mm') or 0.0,
                    'is_auto': leaf.get('is_auto', False),
                    # A container carries no type or direction; its
                    # children do.
                    'leaf_type_id': (
                        False if leaf.get('rows')
                        else leaf.get('leaf_type_id')),
                    'hinge_side': leaf.get('hinge_side') or False,
                    'swing': leaf.get('swing') or False,
                    'slide_dir': leaf.get('slide_dir') or False,
                    'junction_after': leaf.get('junction_after') or False,
                    'track_no': leaf.get('track_no') or 0,
                    'mesh_type_id': leaf.get('mesh_type_id') or False,
                    'mesh_hinge_side': leaf.get('mesh_hinge_side') or False,
                    'infill_type_id': leaf.get('infill_type_id') or False,
                    'glass_spec_id': leaf.get('glass_spec_id') or False,
                    'grid_pattern_id': leaf.get('grid_pattern_id') or False,
                    'grid_rows': leaf.get('grid_rows') or 0,
                    'grid_cols': leaf.get('grid_cols') or 0,
                }) for leaf in row.get('leaves') or []],
            })
            for leaf_payload, leaf in zip(
                    row.get('leaves') or [], record.leaf_ids):
                if leaf_payload.get('rows'):
                    self._create_rows(
                        leaf_payload['rows'], parent_leaf=leaf,
                        depth=depth + 1)

    def save_layout(self, payload):
        """Replace the whole row/leaf grid and the header in ONE call, so
        it's one transaction: either the new layout lands complete or the
        old one is untouched. The client sends the finished state rather
        than a stream of small ORM writes, which would leave a design
        half-rebuilt if the browser died midway.

        Leaf-type legality against the Series is deliberately NOT enforced
        here -- that stays with the checks/validation step, consistent with
        how aw.design.leaf has always treated it. The chips in the UI are
        filtered; this is not a security boundary, only a business rule.
        """
        self.ensure_one()
        incoming = payload.get('header') or {}
        header = {
            key: value for key, value in incoming.items()
            if key in self.CONFIGURATOR_HEADER_FIELDS
        }
        # A field that was never sent is not a field set to empty.
        unsent = [key for key in self.CONFIGURATOR_PROTECTED_HEADER
                  if header.get(key, None) is None]
        for key in unsent:
            header.pop(key, None)
        if header:
            self.write(header)
        # Only ever refills what was NOT sent, so clearing a value from
        # the UI still works and is not undone here.
        self._apply_header_defaults(unsent)

        self.row_ids.unlink()
        self._create_rows(payload.get('rows') or [], parent_leaf=None)
        # Authoritative numbering: the client numbers panels the same way
        # for display, but the server decides what's stored, so a payload
        # that arrived with stale or absent numbers still lands numbered.
        self._renumber_panels()
        # Validated here, once, over the finished tree -- NOT by a
        # constraint on the leaf. A container leaf is created before its
        # sub-rows exist (they need its id), so at create time it looks
        # exactly like a typeless panel and a per-record constraint
        # rejected every horizontal split.
        self._check_panels_typed()
        # Spec 6.5: the BOM is regenerated on every save, so the
        # right-hand panel always shows THIS layout's, never the previous
        # one's. The button stays for a manual re-run.
        self._explode()
        return self.get_configurator_data()

    def _apply_header_defaults(self, fields_to_fill):
        """Backstop for a header field that arrived empty: take the
        Series' answer rather than leaving the design unusable.

        Belt and braces on top of dropping unsent keys. A design with no
        Profile Section produces no profiles at all, so if one ever does
        end up empty -- however it got there -- the Series' first section
        is a far better state to be in than a silently empty BOM.
        """
        self.ensure_one()
        series = self.window_series_id
        if not series:
            return
        defaults = {
            'profile_section_id': series.profile_section_ids[:1],
            'hardware_set_id': series.hardware_set_ids[:1],
            'glass_spec_id': series.default_glass_spec_id,
        }
        values = {}
        for key in fields_to_fill:
            fallback = defaults.get(key)
            if fallback and not self[key]:
                values[key] = fallback.id
        if values:
            self.write(values)

    def _check_panels_typed(self):
        """Every leaf must either be a panel with a type or a container
        with sub-rows. Runs after numbering so the message can name the
        panel, which is what makes it actionable if it ever fires."""
        missing = []

        def walk(rows):
            for row in rows:
                for leaf in row.leaf_ids:
                    if leaf.child_row_ids:
                        walk(leaf.child_row_ids)
                    elif not leaf.leaf_type_id:
                        missing.append(leaf.panel_no)

        for design in self:
            walk(design.row_ids)
            if missing:
                raise UserError(_(
                    "These panels need a leaf type:\n%s",
                    '\n'.join('- Panel %s' % n for n in missing)))

    # -- catalog actions (spec 4.3, 4.5) -----------------------------------
    def _layout_json_from_rows(self, rows):
        """Turn the stored geometry back into a preset layout.

        Sizes become RELATIVE weights, which is the whole point of a
        preset: the mm are used directly because weights are normalised
        per row anyway, so 1200/600 and 2/1 describe the same shape.
        Nesting, junctions and tracks all come along.
        """
        out = []
        for row in rows:
            leaves = []
            for leaf in row.leaf_ids:
                entry = {'w': round(leaf.width_mm or 0, 1)}
                if leaf.child_row_ids:
                    entry['rows'] = self._layout_json_from_rows(
                        leaf.child_row_ids)
                else:
                    entry['type'] = leaf.leaf_type_id.code or ''
                    if leaf.hinge_side:
                        entry['hinge'] = leaf.hinge_side
                    if leaf.swing:
                        entry['swing'] = leaf.swing
                    if leaf.slide_dir:
                        entry['slide'] = leaf.slide_dir
                    if leaf.track_no:
                        entry['track'] = leaf.track_no
                if leaf.junction_after:
                    entry['junction'] = leaf.junction_after
                leaves.append(entry)
            out.append({'h': round(row.height_mm or 0, 1), 'leaves': leaves})
        return out

